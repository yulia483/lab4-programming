"""
 Игра «Угадай число»
 """
 
# Подключаем модуль для работы со случайными числами
import random
a=random.randint(1,100)
while True: # Бесконечный цикл, пока не угадают
    b=int(input("пользователь вводит число: "))
    if a>b:
        print("загаданное число больше")
    elif a<b:
        print("загаданное число меньше")
    else:
        print("число удано")
