a = float(input("введите свой рост(м)"))
b = float(input("введите свой вес(кг)"))
# Проверка на корректность ввода (защита от деления на ноль)
if a <= 0 and b <= 0:
    print("ошибка: значения должны быть > 0")
else:
    i = b / (a**2)
    print(f"ваш имт: {i:.2f}")
    if i < 18.5:
        print("недостаточный вес")
    elif 18.5 <= i <= 24.9:
        print("норма")
    elif 25 <= i <= 29.9:
        print("избыточный вес")
    else:
        print("ожирение")
